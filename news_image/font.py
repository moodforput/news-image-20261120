def text_width(text, scale):
    """Return the pixel width of text at the given integer scale."""
    if not text:
        return 0
    return len(text) * 5 * scale + (len(text) - 1) * scale


def text_height(scale):
    return 7 * scale


def draw_text(canvas, x, y, text, color, scale):
    """Draw uppercase text at (x, y) with the given colour and scale."""
    cursor = x
    for char in text.upper():
        glyph = GLYPHS.get(char)
        if glyph is None:
            cursor += 6 * scale
            continue
        for row_index, row in enumerate(glyph):
            for col_index, bit in enumerate(row):
                if bit == "1":
                    canvas.fill_rect(
                        cursor + col_index * scale,
                        y + row_index * scale,
                        scale,
                        scale,
                        color,
                    )
        cursor += 6 * scale


def draw_text_centred(canvas, centre_x, y, text, color, scale):
    width = text_width(text, scale)
    draw_text(canvas, centre_x - width // 2, y, text, color, scale)
